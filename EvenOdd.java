
public class EvenOdd {

	public static void main (String args[]) {
		int x = 15;
		if (x%2==0){
			System.out.println("The number "+x+" is even");
		}
		else {
			System.out.println("The number "+x+" is odd");
		}
		x = 44;
		if (x%2==0){
			System.out.println("The number "+x+" is even");
		}
		else {
			System.out.println("The number "+x+" is odd");
		}
	}
}

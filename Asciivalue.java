
public class Asciivalue {

	public static void main (String args[]) {
		char first ='b';
		int ascii = first;
		System.out.println("The ASCII value for "+first+ " is: "+ascii);
		
		first ='V';
		ascii = first;
		System.out.println("The ASCII value for "+first+" is: "+ascii);
		
		first= 'x';
		ascii= first;
		System.out.println("The ASCII value for "+first+" is: "+ascii);
		
		first = 'y';
		ascii = first;
		System.out.println("The ASCII value for "+first+" is: "+ascii);
	}
}

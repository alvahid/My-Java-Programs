
public class Operations {

	public static void main(String args[]) {
		int u=20;
		int g=10;
		int y=u*g;
		System.out.println("The two numbers are 20,10 ");
		
		System.out.println("Multiplication of 20 and 10: "+y);
		
		int dc=u+g;
		System.out.println("The addition of 20 and 10 is: "+dc);
		
		int e=u-g;
		System.out.println("Substraction of 20 and 10 is: "+e);
		
		int gf=u/g;
		System.out.println("Division of 20 and 10 is: "+gf);
		
		int yu=u%g;
		System.out.println("Remainder by dividing 20 and 10 is: "+yu);
		
	}
}


public class TernaryOp {

	public static void main (String args[]) {
		
		int z=12;
		int y =19;
		String a = (z==12)?"The operation is true & number equals 12 ":"The operation is False & not equals 12";
		String b = (y==20)?"The operation is true & number equals 19 ":"The operation is False & not equals 19";
		
		System.out.println(a +'\n'+ b);
		
	}
}
